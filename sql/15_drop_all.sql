-- File:    15_drop_all.sql
-- Purpose: Drop every HMS object in reverse dependency order so the
--          schema can be rebuilt from scratch.
-- Author:  HMS Project
-- Date:    2025
-- Notes:   - Each DROP is wrapped in BEGIN...EXECUTE IMMEDIATE...EXCEPTION
--          WHEN OTHERS THEN NULL so a missing object does not abort.
